package report

import (
	"fmt"
	"io"
	"strings"

	"github.com/mustafainci067-cell/linsec-audit/internal/engine"
)

// WriteRemediation emits a commented, idempotent Bash hardening script for failed findings.
func WriteRemediation(w io.Writer, res engine.AuditResult) error {
	var b strings.Builder

	b.WriteString("#!/usr/bin/env bash\n")
	b.WriteString("# Auto-generated by linsec-audit\n")
	fmt.Fprintf(&b, "# Target Host : %s (%s/%s)\n", res.Hostname, res.OS, res.Arch)
	fmt.Fprintf(&b, "# Generated   : %s UTC\n", res.Timestamp.Format("2006-01-02 15:04:05"))
	fmt.Fprintf(&b, "# Audit Score : %d/100 (Grade %s, Risk %s)\n", res.Summary.Score, res.Summary.Grade, res.Summary.RiskLevel)
	b.WriteString("# Review every command carefully before running on production hosts.\n\n")
	b.WriteString("set -uo pipefail\n\n")

	b.WriteString("if [[ \"${EUID}\" -ne 0 ]]; then\n")
	b.WriteString("    echo \"[ERROR] Please run this remediation script as root (sudo bash $0).\" >&2\n")
	b.WriteString("    exit 1\n")
	b.WriteString("fi\n\n")

	failed := 0
	for _, f := range res.Findings {
		if !f.Passed && strings.TrimSpace(f.Remediation) != "" {
			failed++
		}
	}

	if failed == 0 {
		b.WriteString("echo \"[OK] No failed findings to remediate (score: 100/100).\"\n")
		_, err := io.WriteString(w, b.String())
		return err
	}

	b.WriteString("BACKUP_DIR=\"/var/backups/linsec-audit-$(date +%Y%m%d-%H%M%S)\"\n")
	b.WriteString("mkdir -p \"${BACKUP_DIR}\"\n")
	b.WriteString("for cfg in /etc/ssh/sshd_config /etc/passwd /etc/shadow /etc/sudoers /etc/login.defs /etc/ufw/ufw.conf; do\n")
	b.WriteString("    if [[ -f \"${cfg}\" ]]; then\n")
	b.WriteString("        cp -p \"${cfg}\" \"${BACKUP_DIR}/$(basename \"${cfg}\").bak\" 2>/dev/null || true\n")
	b.WriteString("    fi\n")
	b.WriteString("done\n")
	b.WriteString("echo \"[*] Configuration backups saved to ${BACKUP_DIR}\"\n\n")

	b.WriteString("APPLIED=0\n")
	b.WriteString("WARNED=0\n\n")

	for _, f := range res.Findings {
		if f.Passed || strings.TrimSpace(f.Remediation) == "" {
			continue
		}
		fmt.Fprintf(&b, "# [%s] (%s | %s) %s\n", f.ID, f.Severity, f.CISRef, f.Title)
		fmt.Fprintf(&b, "# Actual: %s | Expected: %s\n", sanitizeComment(f.Actual), sanitizeComment(f.Expected))
		fmt.Fprintf(&b, "echo \"[*] Applying %s: %s\"\n", f.ID, sanitizeDoubleQuoted(f.Title))
		b.WriteString("if (\n")
		fmt.Fprintf(&b, "    %s\n", f.Remediation)
		b.WriteString("); then\n")
		fmt.Fprintf(&b, "    echo \"[OK] %s applied\"\n", f.ID)
		b.WriteString("    APPLIED=$((APPLIED + 1))\n")
		b.WriteString("else\n")
		fmt.Fprintf(&b, "    echo \"[WARN] %s returned non-zero status; verify manually\" >&2\n", f.ID)
		b.WriteString("    WARNED=$((WARNED + 1))\n")
		b.WriteString("fi\n\n")
	}

	b.WriteString("# Validate SSH daemon syntax if sshd is available\n")
	b.WriteString("if command -v sshd >/dev/null 2>&1 && [[ -f /etc/ssh/sshd_config ]]; then\n")
	b.WriteString("    if sshd -t 2>/dev/null; then\n")
	b.WriteString("        echo \"[OK] sshd -t syntax validation succeeded\"\n")
	b.WriteString("    else\n")
	b.WriteString("        echo \"[WARN] sshd -t reported configuration warnings\" >&2\n")
	b.WriteString("    fi\n")
	b.WriteString("fi\n\n")
	b.WriteString("echo \"[*] Remediation finished. Applied: ${APPLIED}, Warnings: ${WARNED}\"\n")

	_, err := io.WriteString(w, b.String())
	return err
}

func sanitizeComment(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "\r", " "), "\n", " ")
}

func sanitizeDoubleQuoted(s string) string {
	s = sanitizeComment(s)
	s = strings.ReplaceAll(s, `"`, `'`)
	s = strings.ReplaceAll(s, "$", "")
	s = strings.ReplaceAll(s, "`", "'")
	return s
}
